# Ground truth genres parsing
def parse_genres(listed_in_str):
    if not isinstance(listed_in_str, str):
        return set()
    return {g.strip().lower() for g in listed_in_str.split(',') if g.strip()}

genre_sets = df['listed_in'].apply(parse_genres).values
show_ids = df['show_id'].values

# Shared Evaluation Metric: Precision@10 & NDCG@10
discounts = 1.0 / np.log2(np.arange(1, 11) + 1)
ideal_dcg = np.array([discounts[:i].sum() for i in range(11)])

def evaluate_recs(query_indices, top10_matrix, genre_list):
    precisions = []
    ndcgs = []
    for i, q_idx in enumerate(query_indices):
        q_g = genre_list[q_idx]
        if not q_g:
            continue
        recs = top10_matrix[i]
        hits = np.array([1 if not q_g.isdisjoint(genre_list[r]) else 0 for r in recs])
        hit_sum = hits.sum()
        precisions.append(hit_sum / 10.0)
        dcg = (hits * discounts).sum()
        idcg = ideal_dcg[min(10, hit_sum)]
        ndcgs.append(dcg / idcg if idcg > 0 else 0.0)
    return {
        "precision@10": float(np.mean(precisions)),
        "ndcg@10": float(np.mean(ndcgs))
    }

